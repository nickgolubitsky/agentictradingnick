"""Run round 5 (PREREGISTRATION-round5.md) and write results/round5.md and results/round5.json."""

import datetime as dt
import json
import os
import sys

from . import crypto_data, round5, stats
from .run import OUT, fmt, rel_drawdown

SPLIT = int(dt.datetime(2023, 1, 1, tzinfo=dt.timezone.utc).timestamp())
SPREADS = (0.019, 0.010, 0.005)
YEAR = 365.25 * 86400


def curve(times, equity):
    years = (times[-1] - times[0]) / YEAR
    c = (equity[-1] / equity[0]) ** (1 / years) - 1
    dd = rel_drawdown(equity)
    return {"cagr": c, "max_dd": dd, "ratio": c / dd if dd else float("nan")}


def breakeven(bars, variant):
    """Spread at which the OOS mean net trade crosses zero (bisection on [0, 5%])."""
    def mean_at(s):
        tr = round5.simulate(bars, variant, s, start=SPLIT)["trades"]
        return stats.mean([t["net"] for t in tr]) if tr else float("nan")
    lo, hi = 0.0, 0.05
    if not mean_at(lo) > 0:
        return 0.0
    for _ in range(14):
        mid = (lo + hi) / 2
        if mean_at(mid) > 0:
            lo = mid
        else:
            hi = mid
    return lo


def main():
    raw = {p: crypto_data.fetch(p) for p in crypto_data.PAIRS}
    bars = {p: crypto_data.clean(r) for p, r in raw.items()}
    fixed = {p: sum(1 for a, b in zip(raw[p], bars[p]) if a[1] != b[1]) for p in raw}
    span = {p: (dt.datetime.utcfromtimestamp(r[0][0]).date(), dt.datetime.utcfromtimestamp(r[-1][0]).date())
            for p, r in bars.items()}
    res = {"generated": dt.date.today().isoformat(), "span": span, "variants": {}, "benchmarks": {}}
    bt, be = round5.buy_and_hold(bars, 0.019, start=SPLIT)
    btc_t, btc_e = round5.buy_and_hold({"BTC-USD": bars["BTC-USD"]}, 0.019, start=SPLIT)
    ew, btc = curve(bt, be), curve(btc_t, btc_e)
    res["benchmarks"] = {"equal_weight": ew, "btc": btc}

    L = ["# Backtest results: round 5 (crypto)", "",
         "Generated by `py -m backtest.run5`. Rules: [PREREGISTRATION-round5.md](../backtest/PREREGISTRATION-round5.md).",
         "Coinbase hourly mid prices; Robinhood fills modelled on the ask (buys) and bid (sells). "
         "Out-of-sample = 2023-01-01 → 2026-10-25. Data: " +
         ", ".join("%s %s → %s" % (p, a, b) for p, (a, b) in span.items()) + ".",
         "Bad opening prints reset to the prior close (`crypto_data.clean`): " +
         ", ".join("%s %d" % (p, n) for p, n in fixed.items()) + ".", "",
         "**Benchmarks (OOS, 1.9%% spread paid once):** equal-weight BTC/ETH/SOL/DOGE buy & hold %s CAGR, "
         "%s max DD (CAGR/DD %s); BTC buy & hold %s CAGR, %s max DD." % (
             fmt(ew["cagr"], pct=True), fmt(ew["max_dd"], pct=True), fmt(ew["ratio"], nd=2),
             fmt(btc["cagr"], pct=True), fmt(btc["max_dd"], pct=True)), "",
         "| id | rule | spread | IS mean | OOS trades | win % | mean net | worst | avg hours | t | CAGR | max DD | CAGR/DD | break-even spread | verdict |",
         "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for vid, v in round5.VARIANTS.items():
        rule = ("market buy at 00:00" if v["dip"] is None else "limit −%d%%" % round(v["dip"] * 100)) + \
               ", +%d%% net" % round(v["target"] * 100) + (", stop −10%" if v["stop"] else "")
        be_s = breakeven(bars, vid)
        for s in SPREADS:
            oos = round5.simulate(bars, vid, s, start=SPLIT)
            ins = round5.simulate(bars, vid, s, end=SPLIT)
            tr = oos["trades"]
            st = stats.summarize(tr)
            cv = curve(oos["times"], oos["equity"])
            worst = min((t["net"] for t in tr), default=float("nan"))
            hours = stats.mean([t["hours"] for t in tr]) if tr else float("nan")
            is_mean = stats.mean([t["net"] for t in ins["trades"]]) if ins["trades"] else float("nan")
            if s == SPREADS[0]:
                edge = st["mean"] > 0 and st["t_day"] >= 3.0 and st["trades"] >= 100
                v_ = ("PASS: beats buy & hold" if edge and cv["cagr"] > ew["cagr"] else
                      "PASS: lower risk only" if edge and cv["ratio"] > ew["ratio"] else "FAIL")
            else:
                v_ = "–"
            res["variants"]["%s@%.3f" % (vid, s)] = dict(trades=st, curve=cv, worst=worst, hours=hours,
                                                        is_mean=is_mean, breakeven=be_s, verdict=v_)
            L.append("| %s | %s | %.1f%% | %s | %d | %s | %s | %s | %.0f | %s | %s | %s | %s | %s | %s |" % (
                vid, rule, s * 100, fmt(is_mean, pct=True), st["trades"], fmt(st["win_rate"], pct=True),
                fmt(st["mean"], pct=True), fmt(worst, pct=True), hours, fmt(st["t_day"], nd=2),
                fmt(cv["cagr"], pct=True), fmt(cv["max_dd"], pct=True), fmt(cv["ratio"], nd=2),
                fmt(be_s, pct=True), v_))
    L.append("")
    with open(os.path.join(OUT, "round5.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(L))
    with open(os.path.join(OUT, "round5.json"), "w", encoding="utf-8") as f:
        json.dump(res, f, indent=1, default=str)
    sys.stdout.reconfigure(encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()

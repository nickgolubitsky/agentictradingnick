"""Run round 2 (PREREGISTRATION-round2.md) and write results/round2.md and results/round2.json."""

import datetime as dt
import json
import math
import os
import sys

from . import data, portfolio, stats
from .run import OUT, cagr, fmt, rel_drawdown

UNTOUCHED_END = dt.date(2016, 10, 24)   # primary window ends 2016-10-21, the last session before this
RECENT = (dt.date(2016, 10, 24), dt.date(2026, 10, 24))
COSTS = {"primary": (10, 2), "sensitivity": (20, 5)}
SYMBOLS = ["SPY", "QQQ"]


def curve_stats(dates, eq):
    c, dd = cagr(eq, dates), rel_drawdown(eq)
    return {"cagr": c, "max_dd": dd, "ratio": c / dd if dd else float("nan")}


def portfolio_verdict(mode, s, bh):
    if mode == "D1":
        return "PASS" if s["ratio"] > bh["ratio"] else "FAIL"
    if mode == "D2":
        return "PASS" if s["cagr"] > bh["cagr"] and s["ratio"] >= bh["ratio"] else "FAIL"
    return ""


def main():
    irx = portfolio.irx_lookup(data.daily_bars(data.fetch("^IRX", "max")))
    bars = {s: data.daily_bars(data.fetch(s, "max")) for s in SYMBOLS}
    results = {"generated": dt.date.today().isoformat(), "signal": {}, "portfolio": {}}
    lines = ["# Backtest results: round 2", "",
             "Generated by `py -m backtest.run2`. Rules: [PREREGISTRATION-round2.md](../backtest/PREREGISTRATION-round2.md).",
             "Verdicts use the untouched window only (data before 2016-10-24). The recent window is descriptive.", ""]

    lines += ["## Signal test: RSI(2), C, untouched window", "",
              "| symbol | costs (pre/post 2001-04-09) | window | trades | mean trade | win % | PF | avg days held | t | verdict |",
              "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for sym in SYMBOLS:
        for label, (pre, post) in COSTS.items():
            cost = portfolio.cost_schedule(pre, post)
            tr = portfolio.trade_list(bars[sym], cost, end=UNTOUCHED_END)
            s = stats.summarize(tr)
            v = stats.verdict(s, min_trades=100)
            avg_days = sum(t["days"] for t in tr) / len(tr) if tr else float("nan")
            results["signal"]["%s@%s" % (sym, label)] = dict(s, verdict=v, first=str(tr[0]["date"]),
                                                             last=str(tr[-1]["exit_date"]))
            lines.append("| %s | %d / %d bp (%s) | %s → %s | %d | %s | %s | %s | %.1f | %s | %s |" % (
                sym, pre, post, label, tr[0]["date"], tr[-1]["exit_date"], s["trades"],
                fmt(s["mean"], pct=True), fmt(s["win_rate"], pct=True), fmt(s["profit_factor"], nd=2),
                avg_days, fmt(s["t_day"], nd=2), v))
    lines.append("")

    for title, start, end, judged in (("untouched window (verdicts)", None, UNTOUCHED_END, True),
                                      ("recent window 2016-10-24 → 2026-10-23 (descriptive)", RECENT[0], RECENT[1], False)):
        lines += ["## Portfolio forms: %s" % title, "",
                  "| symbol | form | costs | span | CAGR | max DD | CAGR/DD | verdict |",
                  "| --- | --- | --- | --- | --- | --- | --- | --- |"]
        for sym in SYMBOLS:
            for label, (pre, post) in COSTS.items():
                cost = portfolio.cost_schedule(pre, post)
                d, bh_eq = portfolio.simulate(bars[sym], "BH", cost, start=start, end=end)
                bh = curve_stats(d, bh_eq)
                rows = [("BH", bh)]
                for mode in ("C", "D1", "D2"):
                    dd, eq = portfolio.simulate(bars[sym], mode, cost, rate=irx, start=start, end=end)
                    rows.append((mode, curve_stats(dd, eq)))
                for mode, s in rows:
                    v = portfolio_verdict(mode, s, bh) if judged else ""
                    key = "%s@%s@%s@%s" % (sym, mode, label, "untouched" if judged else "recent")
                    results["portfolio"][key] = dict(s, verdict=v)
                    name = {"BH": "buy & hold", "C": "C (cash idle)", "D1": "D1 (T-bills idle)",
                            "D2": "D2 (B&H + 2× on signal)"}[mode]
                    lines.append("| %s | %s | %s | %s → %s | %s | %s | %s | %s |" % (
                        sym, name, label, d[0], d[-1], fmt(s["cagr"], pct=True), fmt(s["max_dd"], pct=True),
                        fmt(s["ratio"], nd=2), v or "–"))
        lines.append("")

    with open(os.path.join(OUT, "round2.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    with open(os.path.join(OUT, "round2.json"), "w", encoding="utf-8") as f:
        json.dump(results, f, indent=1, default=str)
    sys.stdout.reconfigure(encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()

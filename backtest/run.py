"""Run every round-1 strategy from the cache and write results/round1.md and results/round1.json."""

import datetime as dt
import json
import math
import os
import sys

from . import daily, data, orb, stats
from .universe import ETFS, RSI2_SYMBOLS, STOCKS

DAILY_SPLIT = dt.date(2021, 10, 25)
COSTS = (2, 5)
OUT = os.path.join(data.ROOT, "results")


def load(kind, symbols):
    got, missing = {}, []
    for s in symbols:
        try:
            got[s] = data.fetch(s, kind)
        except data.FetchError as e:
            missing.append("%s (%s)" % (s, e))
    return got, missing


def rel_drawdown(curve):
    peak, mdd = 0.0, 0.0
    for v in curve:
        peak = max(peak, v)
        mdd = max(mdd, (peak - v) / peak)
    return mdd


def cagr(curve, dates):
    years = (dates[-1] - dates[0]).days / 365.25
    return (curve[-1] / curve[0]) ** (1 / years) - 1 if years > 0 else float("nan")


def fmt(x, pct=False, nd=3):
    if x is None or (isinstance(x, float) and (math.isnan(x) or math.isinf(x))):
        return "–" if x is None or math.isnan(x) else "∞"
    return ("%.2f%%" % (100 * x)) if pct else ("%.*f" % (nd, x))


def main():
    os.makedirs(OUT, exist_ok=True)
    results = {"generated": dt.date.today().isoformat(), "orb": {}, "setups": {}, "rsi2": {}}
    lines = ["# Backtest results: round 1", "",
             "Generated by `python -m backtest.run`. Rules are in [PREREGISTRATION.md](../backtest/PREREGISTRATION.md).",
             "Verdicts use the out-of-sample (OOS) half only. t = day-clustered t-stat; PASS needs t ≥ 3.0.", ""]

    # ---- A: opening-range breakout
    raw, missing_i = load("intraday", STOCKS)
    sessions = {s: data.intraday_sessions(r) for s, r in raw.items()}
    all_days = sorted({d for v in sessions.values() for d in v})
    cut = all_days[len(all_days) // 2]
    results["orb"]["window"] = [str(all_days[0]), str(all_days[-1]), len(all_days), str(cut)]
    lines += ["## A. Opening-range breakout (5-minute bars)", "",
              "%d symbols, %d full sessions from %s to %s. IS before %s, OOS from %s." % (
                  len(sessions), len(all_days), all_days[0], all_days[-1], cut, cut), ""]
    if missing_i:
        lines += ["Missing: " + ", ".join(missing_i), ""]
    lines += ["| id | rule | cost/side | IS trades | IS mean R | OOS trades | OOS days | OOS mean R | OOS win % | OOS PF | OOS t | verdict |",
              "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for vid in ("A1", "A2", "A3", "A4", "A0"):
        v = orb.VARIANTS[vid]
        rule = ("control, " if v.get("control") else "") + "stop %s, %gR" % (v["stop"], v["target_r"])
        for cost in COSTS:
            tr = orb.run(sessions, vid, cost)
            s_is = stats.summarize([t for t in tr if t["date"] < cut])
            s_oos = stats.summarize([t for t in tr if t["date"] >= cut])
            verdict = stats.verdict(s_oos)
            results["orb"]["%s@%d" % (vid, cost)] = {"is": s_is, "oos": s_oos, "verdict": verdict}
            lines.append("| %s | %s | %d bp | %d | %s | %d | %d | %s | %s | %s | %s | %s |" % (
                vid, rule, cost, s_is["trades"], fmt(s_is["mean"]), s_oos["trades"], s_oos["days"],
                fmt(s_oos["mean"]), fmt(s_oos["win_rate"], pct=True), fmt(s_oos["profit_factor"], nd=2),
                fmt(s_oos["t_day"], nd=2), verdict))
    lines.append("")

    # ---- B: daily scanner setups
    raw_d, missing_d = load("daily", STOCKS + ETFS)
    bars = {s: data.daily_bars(r) for s, r in raw_d.items()}
    span = (min(b[0][0] for b in bars.values()), max(b[-1][0] for b in bars.values()))
    lines += ["## B. Daily scanner setups (enter next open, hold 5 sessions)", "",
              "%d symbols, %s to %s. IS before %s. Edge = return minus the same-day baseline "
              "(every symbol, every day, same hold). t uses Newey-West lag 4 for the overlapping holds." % (
                  len(bars), span[0], span[1], DAILY_SPLIT), ""]
    if missing_d:
        lines += ["Missing: " + ", ".join(missing_d), ""]
    lines += ["| setup | cost/side | IS trades | IS edge | OOS trades | OOS mean return | OOS edge | OOS edge t | verdict |",
              "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for cost in COSTS:
        events, base = daily.scan_events(bars, cost)
        b_oos = stats.summarize([r for r in base if r["date"] >= DAILY_SPLIT], lag=4)
        results["setups"]["baseline@%d" % cost] = {"oos": b_oos}
        lines.append("| *baseline (every day)* | %d bp | – | – | %d | %s | 0 | – | – |" % (
            cost, b_oos["trades"], fmt(b_oos["mean"], pct=True)))
        for k in daily.SETUPS:
            ev = events[k]
            e_is = stats.summarize([r for r in ev if r["date"] < DAILY_SPLIT], value="excess", lag=4)
            oos = [r for r in ev if r["date"] >= DAILY_SPLIT]
            e_oos = stats.summarize(oos, value="excess", lag=4)
            n_oos = stats.summarize(oos, value="net", lag=4)
            verdict = stats.verdict(e_oos)
            results["setups"]["%s@%d" % (k, cost)] = {"is_excess": e_is, "oos_excess": e_oos,
                                                       "oos_net": n_oos, "verdict": verdict}
            lines.append("| %s | %d bp | %d | %s | %d | %s | %s | %s | %s |" % (
                k, cost, e_is["trades"], fmt(e_is["mean"], pct=True), e_oos["trades"],
                fmt(n_oos["mean"], pct=True), fmt(e_oos["mean"], pct=True), fmt(e_oos["t_day"], nd=2), verdict))
    lines.append("")

    # ---- C: RSI(2)
    lines += ["## C. RSI(2) mean reversion vs buy-and-hold (OOS window)", "",
              "| symbol | cost/side | OOS trades | mean trade | win % | t | CAGR | max DD | CAGR/DD | B&H CAGR | B&H max DD | B&H CAGR/DD | time in market | verdict |",
              "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for sym in RSI2_SYMBOLS:
        if sym not in bars:
            lines.append("| %s | missing | | | | | | | | | | | | |" % sym)
            continue
        for cost in COSTS:
            tr, eq, bh, dates = daily.rsi2(bars[sym], cost, start=DAILY_SPLIT)
            s = stats.summarize(tr)
            in_mkt = sum(1 for a, b in zip(eq[1:], eq[:-1]) if a != b) / max(1, len(eq) - 1)
            c_s, c_b = cagr(eq, dates), cagr(bh, dates)
            d_s, d_b = rel_drawdown(eq), rel_drawdown(bh)
            ratio_s = c_s / d_s if d_s else float("nan")
            ratio_b = c_b / d_b if d_b else float("nan")
            verdict = stats.verdict(s, min_trades=100)
            if verdict == "PASS" and not ratio_s > ratio_b:
                verdict = "FAIL (B&H better)"
            results["rsi2"]["%s@%d" % (sym, cost)] = {"oos": s, "cagr": c_s, "max_dd": d_s, "bh_cagr": c_b,
                                                     "bh_max_dd": d_b, "verdict": verdict}
            lines.append("| %s | %d bp | %d | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
                sym, cost, s["trades"], fmt(s["mean"], pct=True), fmt(s["win_rate"], pct=True),
                fmt(s["t_day"], nd=2), fmt(c_s, pct=True), fmt(d_s, pct=True), fmt(ratio_s, nd=2),
                fmt(c_b, pct=True), fmt(d_b, pct=True), fmt(ratio_b, nd=2), fmt(in_mkt, pct=True), verdict))
    lines.append("")

    with open(os.path.join(OUT, "round1.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    with open(os.path.join(OUT, "round1.json"), "w", encoding="utf-8") as f:
        json.dump(results, f, indent=1, default=str)
    sys.stdout.reconfigure(encoding="utf-8")  # the Windows console defaults to cp1252
    print("\n".join(lines))


if __name__ == "__main__":
    main()

"""Run round 4 (PREREGISTRATION-round4.md) and write results/round4.md and results/round4.json."""

import datetime as dt
import json
import os
import sys

from . import data, portfolio, round4, stats
from .run import OUT, fmt
from .run2 import COSTS
from .run3 import curve_stats, window
from .universe import ETFS, STOCKS

START = dt.date(2000, 1, 3)
RECENT = dt.date(2016, 10, 24)


def load(symbols, kind):
    out = {}
    for s in symbols:
        try:
            out[s] = round4.indicators(data.daily_bars(data.fetch(s, kind)))
        except data.FetchError:
            pass
    return out


def label(edge_ok, s, spy):
    if not edge_ok:
        return "FAIL"
    if s["cagr"] > spy["cagr"]:
        return "PASS: beats SPY"
    if s["ratio"] > spy["ratio"]:
        return "PASS: lower risk only"
    return "FAIL"


def main():
    irx = portfolio.irx_lookup(data.daily_bars(data.fetch("^IRX", "max")))
    spy = data.daily_bars(data.fetch("SPY", "max"))
    res = {"generated": dt.date.today().isoformat(), "etf": {}, "stk": {}}
    L = ["# Backtest results: round 4", "",
         "Generated by `py -m backtest.run4`. Rules: [PREREGISTRATION-round4.md](../backtest/PREREGISTRATION-round4.md).",
         "Daily engine: up to 5 positions at 20% each, entries ranked most-oversold first, every fill at "
         "the next open, idle cash in T-bills. Sharpe uses a 0% risk-free rate.", "",
         "| universe | signal | costs | window | CAGR | max DD | CAGR/DD | Sharpe | trades | trades/wk | "
         "days with a fill | up days (invested) | mean trade | t | SPY CAGR | SPY CAGR/DD | verdict |",
         "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]

    for uni, symbols, kind, start in (("U-ETF", ETFS, "max", START), ("U-STK", STOCKS, "daily", RECENT)):
        ind = load(symbols, kind)
        calendar = [b[0] for b in spy if b[0] >= start]
        for sig in ("S1", "S2"):
            for clabel, (pre, post) in COSTS.items():
                cost = portfolio.cost_schedule(pre, post)
                r = round4.simulate(ind, calendar, round4.SIGNALS[sig], cost, irx)
                windows = (("full", None), ("last 10y", RECENT)) if uni == "U-ETF" else (("10y", None),)
                for wname, wstart in windows:
                    d, e = window(r["dates"], r["equity"], start=wstart)
                    tr = [t for t in r["trades"] if not wstart or t["date"] >= wstart]
                    sub = {k: [v for x, v in zip(r["dates"], r[k]) if not wstart or x >= wstart]
                           for k in ("fills", "invested")}
                    ds = round4.day_stats(dict(dates=d, equity=e, trades=tr, **sub))
                    cs = curve_stats(d, e)
                    sp_i = next(k for k, b in enumerate(spy) if b[0] == d[0])
                    sd = [b[0] for b in spy[sp_i:] if b[0] <= d[-1]]
                    se = [b[4] / spy[sp_i][4] for b in spy[sp_i:] if b[0] <= d[-1]]
                    sp = curve_stats(sd, se)
                    ts = stats.summarize(tr)
                    if uni == "U-ETF" and wname == "full" and clabel == "primary":
                        recent_mean = stats.mean([t["net"] for t in r["trades"] if t["date"] >= RECENT])
                        edge_ok = (ts["mean"] > 0 and ts["t_day"] >= 3.0 and ts["trades"] >= 100
                                   and recent_mean > 0)
                        v = label(edge_ok, cs, sp)
                    else:
                        v = "descriptive" if uni == "U-STK" else "–"
                    key = "%s@%s@%s@%s" % (uni, sig, clabel, wname)
                    res["etf" if uni == "U-ETF" else "stk"][key] = dict(curve=cs, spy=sp, trades=ts, days=ds, verdict=v)
                    L.append("| %s | %s | %d/%d bp | %s %s → %s | %s | %s | %s | %s | %d | %.1f | %s | %s | %s | %s | %s | %s | %s |" % (
                        uni, sig, pre, post, wname, d[0], d[-1], fmt(cs["cagr"], pct=True), fmt(cs["max_dd"], pct=True),
                        fmt(cs["ratio"], nd=2), fmt(cs["sharpe0"], nd=2), ts["trades"], ds["trades_per_week"],
                        fmt(ds["fill_day_share"], pct=True), fmt(ds["positive_invested_days"], pct=True),
                        fmt(ts["mean"], pct=True), fmt(ts["t_day"], nd=2), fmt(sp["cagr"], pct=True),
                        fmt(sp["ratio"], nd=2), v))
    L.append("")

    with open(os.path.join(OUT, "round4.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(L))
    with open(os.path.join(OUT, "round4.json"), "w", encoding="utf-8") as f:
        json.dump(res, f, indent=1, default=str)
    sys.stdout.reconfigure(encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()

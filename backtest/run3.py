"""Run round 3 (PREREGISTRATION-round3.md) and write results/round3.md and results/round3.json."""

import datetime as dt
import json
import math
import os
import sys

from . import data, portfolio, round3, stats
from .run import OUT, cagr, fmt, rel_drawdown
from .run2 import COSTS, UNTOUCHED_END

RECENT_START = dt.date(2016, 10, 24)


def window(dates, eq, start=None, end=None):
    idx = [k for k, x in enumerate(dates) if (not start or x >= start) and (not end or x < end)]
    base = eq[idx[0]]
    return [dates[k] for k in idx], [eq[k] / base for k in idx]


def curve_stats(dates, eq):
    rets = [b / a - 1 for a, b in zip(eq, eq[1:])]
    m = sum(rets) / len(rets)
    sd = math.sqrt(sum((r - m) ** 2 for r in rets) / (len(rets) - 1))
    c, dd = cagr(eq, dates), rel_drawdown(eq)
    return {"start": str(dates[0]), "end": str(dates[-1]), "cagr": c, "max_dd": dd,
            "ratio": c / dd if dd else float("nan"), "sharpe0": m / sd * math.sqrt(252) if sd else float("nan")}


def row(name, s, verdict="–"):
    return "| %s | %s → %s | %s | %s | %s | %s | %s |" % (
        name, s["start"], s["end"], fmt(s["cagr"], pct=True), fmt(s["max_dd"], pct=True),
        fmt(s["ratio"], nd=2), fmt(s["sharpe0"], nd=2), verdict)


def main():
    irx = portfolio.irx_lookup(data.daily_bars(data.fetch("^IRX", "max")))
    syms = sorted(set(round3.GTAA + ["QQQ"]))
    bars = {s: data.daily_bars(data.fetch(s, "max")) for s in syms}
    res = {"generated": dt.date.today().isoformat(), "r3_1": {}, "r3_2": {}, "r3_3": {}}
    L = ["# Backtest results: round 3", "",
         "Generated by `py -m backtest.run3`. Rules: [PREREGISTRATION-round3.md](../backtest/PREREGISTRATION-round3.md).",
         "Every fill is at an **open**, because Nick places each order by hand the evening before. "
         "Sharpe is annualized from daily returns with a 0% risk-free rate.", ""]

    # ---- R3-1
    L += ["## R3-1. RSI(2) with next-open fills", "",
          "| symbol | costs | window | trades | mean trade | win % | t | close-fill mean | edge kept | verdict |",
          "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for sym in ("SPY", "QQQ"):
        for label, (pre, post) in COSTS.items():
            cost = portfolio.cost_schedule(pre, post)
            for wname, start, end in (("untouched", None, UNTOUCHED_END), ("recent", RECENT_START, None)):
                tr = round3.rsi2_next_open_trades(bars[sym], cost, start=start, end=end)
                close_tr = portfolio.trade_list(bars[sym], cost, start=start, end=end)
                s = stats.summarize(tr)
                cm = stats.mean([t["net"] for t in close_tr])
                v = stats.verdict(s, min_trades=100) if wname == "untouched" else "descriptive"
                res["r3_1"]["%s@%s@%s" % (sym, label, wname)] = dict(s, close_fill_mean=cm, verdict=v)
                L.append("| %s | %d/%d bp | %s %s → %s | %d | %s | %s | %s | %s | %s | %s |" % (
                    sym, pre, post, wname, tr[0]["date"], tr[-1]["exit_date"], s["trades"],
                    fmt(s["mean"], pct=True), fmt(s["win_rate"], pct=True), fmt(s["t_day"], nd=2),
                    fmt(cm, pct=True), fmt(s["mean"] / cm, pct=True) if cm > 0 else "–", v))
    L.append("")

    # ---- R3-2 and R3-3
    for label, (pre, post) in COSTS.items():
        cost = portfolio.cost_schedule(pre, post)
        gd, ge, exposure = round3.gtaa(bars, cost, irx)
        ed, ee, _ = round3.gtaa(bars, cost, irx, always_in=True)
        spy = bars["SPY"]
        first = next(k for k, b in enumerate(spy) if b[0] == gd[0])
        sd = [b[0] for b in spy[first:]]
        se = [b[4] / spy[first][1] for b in spy[first:]]          # bought at the first rebalance open
        rd, re_ = round3.rsi2_next_open_curve(spy, cost, irx)
        rd, re_ = window(rd, re_, start=gd[0])
        bd, be = round3.blend((gd, ge), (rd, re_))

        g, e, b_, r, m = (curve_stats(gd, ge), curve_stats(ed, ee), curve_stats(sd, se),
                          curve_stats(rd, re_), curve_stats(bd, be))
        g_v = "PASS" if g["ratio"] > b_["ratio"] and g["ratio"] > e["ratio"] else "FAIL"
        best_sleeve = max(g["ratio"], r["ratio"])
        m_v = "PASS" if m["ratio"] > b_["ratio"] and m["ratio"] > best_sleeve else "FAIL"
        mg = round3.monthly_returns(gd, ge)
        mr = round3.monthly_returns(rd, re_)
        keys = sorted(set(mg) & set(mr))
        corr = round3.correlation([mg[k] for k in keys], [mr[k] for k in keys])
        avg_exp = sum(x for _, x in exposure) / len(exposure)
        res["r3_2"][label] = {"gtaa": dict(g, verdict=g_v, avg_exposure=avg_exp), "ew": e, "spy": b_}
        res["r3_3"][label] = {"blend": dict(m, verdict=m_v), "rsi2_spy": r, "monthly_corr": corr,
                              "months": len(keys)}

        L += ["## R3-2 / R3-3 at %s costs (%d/%d bp)" % (label, pre, post), "",
              "| curve | span | CAGR | max DD | CAGR/DD | Sharpe | verdict |",
              "| --- | --- | --- | --- | --- | --- | --- |",
              row("SPY buy & hold", b_), row("Equal-weight GTAA-5, always in", e),
              row("**GTAA-5 trend** (R3-2)", g, g_v),
              row("RSI(2) SPY, next open, T-bills idle", r),
              row("**Blend 50/50** (R3-3)", m, m_v), "",
              "GTAA-5 average exposure: %s of the book in assets, the rest in T-bills. "
              "Monthly correlation, GTAA-5 vs RSI(2): %.2f over %d months." % (
                  fmt(avg_exp, pct=True), corr, len(keys)), ""]

    with open(os.path.join(OUT, "round3.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(L))
    with open(os.path.join(OUT, "round3.json"), "w", encoding="utf-8") as f:
        json.dump(res, f, indent=1, default=str)
    sys.stdout.reconfigure(encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
